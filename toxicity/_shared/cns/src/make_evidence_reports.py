def translational_pairing(meas, oligos) -> str:
    by_oligo = collections.defaultdict(set)
    for m in meas:
        by_oligo[m["oligo_id"]].add(m["subject_class"])
    both = [o for o, cs in by_oligo.items() if (cs & HUMAN) and (cs - HUMAN)]

    def seqs(classes):
        ids = {m["oligo_id"] for m in meas if m["subject_class"] in classes}
        return {o["oligo_id"]: o["sequence_base"].strip().upper()
                for o in oligos if o["oligo_id"] in ids
                and o["sequence_base"].strip() not in ("", "NOT_REPORTED")}

    hs, as_ = seqs(HUMAN), seqs({"animal_invitro", "animal_invivo"})
    comp = str.maketrans("ACGTU", "TGCAA")
    exact, contained, revcomp = [], [], []
    for hid, h in hs.items():
        for aid, a in as_.items():
            if h == a:
                exact.append((hid, aid))
            elif h in a or a in h:
                contained.append((hid, aid))
            elif h == a.translate(comp)[::-1]:
                revcomp.append((hid, aid))

    n181 = len({m["oligo_id"] for m in meas if m["source_id"] == "H1"
                and m["subject_class"] == "animal_invivo"})
    return f"""# Translational pairing — what actually bridges systems

*Generated by `src/make_evidence_reports.py`. Do not hand-edit.*

The Challenge prioritises datasets *"based on in vitro human systems or able to extrapolate data
between in vitro human systems and animal data."* Both phrases require human cells on one side.

## The 181-compound pairing is animal to animal

{n181} compounds carry both an *in vitro* and an *in vivo* readout. Both sides come from source
H1: rat primary cortical neuron calcium oscillation, paired to mouse intracerebroventricular
tolerability. Both carry `is_human_system = FALSE`.

It is a genuine and useful in-vitro-to-in-vivo bridge, and it is **not** the bridge the Challenge
asks for. Describing it as satisfying the extrapolation clause is an overclaim, and two documents
in this module did so until 2026-10-02.

## Compounds carrying both a human and an animal row

**{len(both)}.**

| test | matches |
|---|---:|
| Oligos with both a human-system and an animal row | {len(both)} |
| Exact `sequence_base` match, human source ↔ animal source | {len(exact)} |
| Containment (one sequence inside the other) | {len(contained)} |
| Reverse complement | {len(revcomp)} |

Compared {len(hs)} sequence-resolved human-system oligos against {len(as_)} animal ones. The
cross-system compound count is zero by every test, so **no compound in this release has its
toxicity measured in both a human and an animal system.** There is nothing to extrapolate between
yet.

## What would close it

The highest-value acquisition is a compound measured in a human system that is *already* in the
clinical layer. **Ottesen 2026** (PMC12805893, CC BY) reports an 18-mer whose sequence and
chemistry are identical to **nusinersen**, which this dataset already holds as a clinical
compound. Extracting it would create the module's first genuine human-laboratory-to-human-clinical
link on a single molecule. It is queued in `sources/RESEARCH_QUEUE.md`.
"""


