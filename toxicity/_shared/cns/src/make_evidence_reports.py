def characterization(meas, oligos) -> str:
    reach = collections.defaultdict(set)
    for m in meas:
        reach[m["oligo_id"]].add(m["subject_class"])
    hum = {o for o, c in reach.items() if c & HUMAN}
    ani = {o for o, c in reach.items() if (c - HUMAN) and not (c & HUMAN)}
    idx = {o["oligo_id"]: o for o in oligos}

    FIELDS = [("sequence_5to3_asprinted", "Sequence as printed"),
              ("sequence_base", "Nucleobase sequence"),
              ("modification_positions", "Per-position modification map"),
              ("purity_pct", "Purity value"),
              ("purity_method", "Purification method"),
              ("identity_confirmation", "Analytical identity confirmation")]

    def have(ids, f):
        return sum(1 for i in ids if idx.get(i, {}).get(f, "").strip() not in ("", "NOT_REPORTED"))

    src_res = sum(1 for i in hum
                  if idx.get(i, {}).get("modification_position_basis", "").startswith("position_resolved"))
    src_res_a = sum(1 for i in ani
                    if idx.get(i, {}).get("modification_position_basis", "").startswith("position_resolved"))
    rows = "\n".join(
        f"| {lab} | {have(hum, f)} / {len(hum)} | {100*have(hum,f)/len(hum):.0f}% | "
        f"{have(ani, f):,} / {len(ani):,} | {100*have(ani,f)/len(ani):.0f}% |"
        for f, lab in FIELDS)

    return f"""# Characterization coverage — human subset and animal subset, kept apart

*Generated by `src/make_evidence_reports.py`. Do not hand-edit.*

The Challenge requires, per oligonucleotide, the sequence, the location of all chemical
modifications, purity and identity. **Every completeness figure this module published before
2026-10-02 was pooled**, which let a {len(ani):,}-compound rat screen stand in for human
completeness. Pooled figures are not reported here at all.

| | Human-reaching ({len(hum)}) | | Animal-only ({len(ani):,}) | |
|---|---:|---:|---:|---:|
{rows}
| *of those, source-resolved positions* | {src_res} / {len(hum)} | {100*src_res/len(hum):.0f}% | {src_res_a:,} / {len(ani):,} | {100*src_res_a/len(ani):.0f}% |

## Read this honestly

**The human subset is essentially uncharacterized.** Of the {len(hum)} oligonucleotides that reach
a human measurement, {have(hum, 'sequence_5to3_asprinted')} carry a sequence, **{src_res} carry a
source-resolved modification map**, **{have(hum, 'purity_pct')} carry a purity value** and
**{have(hum, 'identity_confirmation')} carry an identity confirmation**. The mandatory
characterization requirement is currently met for the rat screen and not for the data class the
Challenge is built around.

**Purity is zero everywhere**, in both subsets. A purification *method* is recorded for many
compounds; a purity *value* is recorded for none. These are different things and the distinction
is load-bearing — a method says how the material was cleaned, a value says how clean it was. See
`OPEN_ITEMS.md` OI-02.

**A reference sequence is not analytical identity.** Where a sequence was verified against a
publication or an INN description, that establishes what the compound was *intended* to be. It
says nothing about the purity or identity of the material actually dosed in the experiment.

## Recoverable, with a named lead

| Gap | Lead |
|---|---|
| Purity / identity for the HV compounds | supplementary methods of HV1–HV3; vendor certificates of analysis are not in the public record |
| Modification positions for clinical compounds | the published INN descriptions, which print per-position chemistry formally — this is how tofersen's map was obtained |
| Purity / identity for the clinical compounds | not published; vendor certificates of analysis for an investigational oligonucleotide are not in the public record |

**Closed since the first revision of this report.** HV3's 23 sequences were printed in `mmc1.pdf`
Table S2 in LNA notation (`+N` = LNA, `/IDSP/` = abasic DSpacer) and have been parsed into
per-position maps, with the phosphorothioate backbone transcribed from the source's own wording.
That moved human source-resolved modification coverage off zero.

Nothing above is promised. Each is a specific document that may or may not contain the value.
"""


def main() -> int:
    DOCS.mkdir(parents=True, exist_ok=True)
    meas, oligos, trials = load()
    for name, text in (("TRIAL_REGISTER.md", trial_register(meas, oligos, trials)),
                       ("CHRONIC_QUALIFICATION.md", chronic_qualification(meas)),
                       ("TRANSLATIONAL_PAIRING.md", translational_pairing(meas, oligos)),
                       ("CHARACTERIZATION_COVERAGE.md", characterization(meas, oligos))):
        (DOCS / name).write_text(text)
        print(f"wrote docs/{name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
