#!/usr/bin/env python3
"""Emit the OligoTox-CNS summary statistics as Markdown.

The record counters and distribution tables in `README-CNS.md` and
`METHODOLOGY-CNS.md` are generated by this script rather than typed, so the
documentation cannot drift from the data. Re-run it after any change to the
canonical tables and paste the output into the marked blocks.

Usage:  python scripts/dataset_stats_cns.py
        python scripts/dataset_stats_cns.py --check-docs
"""
import csv
import os
import re
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OLIGOS = os.path.join(ROOT, "data", "cns_oligos.csv")
MEAS = os.path.join(ROOT, "data", "cns_measurements.csv")


def load():
    with open(OLIGOS, newline="", encoding="utf-8") as f:
        o = list(csv.DictReader(f))
    with open(MEAS, newline="", encoding="utf-8") as f:
        m = list(csv.DictReader(f))
    return o, m


def lane(r):
    mt = re.match(r"\[([a-z_]+)\]", r["notes"] or "")
    return mt.group(1) if mt else "unknown"


def table(title, counter, total=None):
    out = ["| %s | Rows | Share |" % title, "|---|---:|---:|"]
    tot = total or sum(counter.values())
    for k, v in counter.most_common():
        out.append("| `%s` | %d | %.1f%% |" % (k, v, 100.0 * v / tot))
    return "\n".join(out)


def check_docs():
    """Assert that the numbers hand-written into the docs match the data.

    The counters in README-CNS.md are transcribed from this script's output, and
    transcription is exactly the step this project distrusts everywhere else. A
    dataset whose own README misstates its row count has no business asking anyone
    to trust its 2,329 rows, so the claim is checked rather than assumed.
    """
    o, m = load()
    facts = {
        "oligos": len(o),
        "measurements": len(m),
        "grade0": sum(1 for r in m if r["neurotox_grade"] == "0"),
        "grade3": sum(1 for r in m if r["neurotox_grade"] == "3"),
        "invitro": sum(1 for r in m if r["study_type"] == "in_vitro"),
        "clinical": sum(1 for r in m if r["study_type"] == "clinical"),
        "animal": sum(1 for r in m if r["study_type"] == "animal_invivo"),
        "lowephys": sum(1 for r in m
                        if r["challenge_priority"] == "low_acute_electrophysiology"),
        "hydro": sum(1 for r in m
                     if r["challenge_priority"] == "high_hydrocephalus"),
    }
    bad = []
    # README-CNS.md is the only doc that transcribes counters; METHODOLOGY-CNS.md
    # deliberately defers its distributions to this script rather than repeating them.
    for doc in ("README-CNS.md",):
        path = os.path.join(ROOT, doc)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        nums = {int(x.replace(",", ""))
                for x in re.findall(r"\b\d{1,3}(?:,\d{3})+\b|\b\d{3,5}\b", text)}
        for name, val in facts.items():
            # only check the counts big enough to be unambiguous in prose
            if val >= 100 and val not in nums:
                bad.append("%s: %s=%d appears nowhere" % (doc, name, val))
    for b in bad:
        print("DOC MISMATCH %s" % b)
    print("doc check: %d mismatch(es)" % len(bad))
    return 1 if bad else 0


def main():
    if "--check-docs" in sys.argv:
        raise SystemExit(check_docs())
    o, m = load()
    n_o, n_m = len(o), len(m)

    print("### Record counter\n")
    print("| | Count |")
    print("|---|---:|")
    print("| Unique oligonucleotides (`cns_oligos.csv`) | **%d** |" % n_o)
    print("| Measurement rows (`cns_measurements.csv`) | **%d** |" % n_m)
    seq = sum(1 for r in o if r["sequence_5to3"] not in ("TBD", ""))
    print("| Oligos with a published sequence | **%d / %d** |" % (seq, n_o))
    print("| Distinct target genes | %d |" %
          len({r["target_gene"] for r in o} - {"TBD", "NA", ""}))
    print("| Distinct source documents | %d |" % len({r["source_ref"] for r in m}))
    print("| Strict-CNS rows (`is_cns_specific=TRUE`) | %d |" %
          sum(1 for r in m if r["is_cns_specific"] == "TRUE"))
    print()

    print("### Dependent variable — `neurotox_grade`\n")
    print(table("Grade", Counter(r["neurotox_grade"] for r in m), n_m))
    print()

    print("### Endpoint domain (CNS-specific)\n")
    print(table("Endpoint", Counter(r["endpoint_domain"] for r in m), n_m))
    print()

    print("### Challenge priority\n")
    print(table("Priority", Counter(r["challenge_priority"] for r in m), n_m))
    print()

    print("### Study type, species and delivery route\n")
    for name, key in (("Study type", "study_type"), ("Species", "species"),
                      ("Delivery route", "delivery_method")):
        print(table(name, Counter(r[key] for r in m), n_m))
        print()

    print("### Readout category\n")
    print(table("Readout category", Counter(r["readout_category"] for r in m), n_m))
    print()

    print("### Reversibility\n")
    print(table("Reversibility", Counter(r["reversibility"] for r in m), n_m))
    print()

    print("### Independent variables — oligo design predictors\n")
    for name, key in (("Modality", "oligo_class"), ("Backbone", "backbone_chemistry"),
                      ("Conjugate", "conjugate"), ("Development stage", "max_phase")):
        print(table(name, Counter(r[key] for r in o), n_o))
        print()

    print("### Provenance and redistribution\n")
    print(table("Rights", Counter(r["redistribution"] for r in m), n_m))
    print()

    print("### Contribution by extraction lane\n")
    print(table("Lane", Counter(lane(r) for r in m), n_m))
    print()

    print("### Largest single sources\n")
    print("| Source | Rows | Rights |")
    print("|---|---:|---|")
    c = Counter(r["source_ref"] for r in m)
    rights = {}
    for r in m:
        rights.setdefault(r["source_ref"], r["redistribution"])
    for k, v in c.most_common(12):
        print("| `%s` | %d | `%s` |" % (k, v, rights[k]))
    print()


if __name__ == "__main__":
    main()
